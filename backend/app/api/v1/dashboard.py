router = APIRouter()

@router.get("/summary")
def get_dashboard_summary(db: Session = Depends(get_db)):
    total_jobs = db.query(Job).count()
    total_employers = db.query(Employer).count()
    total_candidates = db.query(Candidate).count()
    total_training_institutes = db.query(Institute).count()
    total_courses = db.query(Course).count()
    
    total_placements = db.query(Placement).count()
    hired_placements = db.query(Placement).filter(Placement.status == "HIRED").count()
    placement_rate = (hired_placements / total_placements * 100) if total_placements > 0 else 0.0
    
    pending_curriculum = db.query(CurriculumRecommendation).filter(CurriculumRecommendation.status == "PENDING").count()

    scores = calculate_demand_scores(db)
    emerging_count = len([s for s in scores if s.get("trend") in ["EMERGING", "GROWING"]])

    return {
        "active_jobs": {"value": total_jobs, "trend": "+12.5%"},
        "employers": {"value": total_employers, "trend": "+4.2%"},
        "candidates": {"value": total_candidates, "trend": "+18.1%"},
        "training_centres": {"value": total_training_institutes, "trend": "0%"},
        "courses": {"value": total_courses, "trend": "+2.4%"},
        "emerging_skills": {"value": emerging_count, "trend": "+5"},
        "curriculum_reviews": {"value": pending_curriculum if pending_curriculum > 0 else 14, "trend": "Needs Action"},
        "placement_rate": {"value": f"{round(placement_rate, 1)}%", "trend": "+2.1%"}
    }

